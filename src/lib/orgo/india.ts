export function findCityPin(state: string | undefined, city: string | undefined): string {
  if (!state || !city) return "";
  const list = STATE_CITIES[state];
  if (!list) return "";
  const hit = list.find((c) => c.name.toLowerCase() === city.trim().toLowerCase());
  return hit ? hit.pin : "";
}
